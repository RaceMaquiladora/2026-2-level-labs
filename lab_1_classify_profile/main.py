def tokenize(text: str) -> Sequence[str] | None:
    if type(text) is not str:
        return None

    text = text.lower()

    for word in text:
            if not word.isalpha() and not word.isspace():
                text = text.replace(word, "")

    tokens = text.split()

    return tokens

def remove_stop_words(tokens: Sequence[str], stop_words: Sequence[str]) -> Sequence[str] | None:
    for token in tokens:
        if type(token) is not str:
            return None


    stops = []

    for word in stop_words:
        stops.append(word)

    for token in tokens:
         if token in stops:
            tokens.remove(token)

    return tokens

def calculate_frequencies(tokens: Sequence[str]) -> dict[str, float] | None:
    freq_dict = FreqDictType()

    for token in tokens:
        if token in freq_dict:
            freq_dict[token] += 1
        else:
            freq_dict[token] = 1

    for key in freq_dict.keys():
        freq_dict[key] = freq_dict[key] / len(tokens)

    return freq_dict

def get_top_n_words(freq_dict: dict[str, float], top_n: int) -> Sequence[str] | None:
    items_sorted = sorted(freq_dict.items(), key=lambda x: x[1], reverse=True)

    top_words = [word for word, _ in items_sorted[:top_n]]

    return top_words


